"""The engines from other projects (engines/<source>/), for the build: scripts/build-emu.sh runs it.

  gen_ext_engines.py ROOT OUT_DIR

Every folder in engines/ with an engines.txt is a source. Its engines.txt lists its engines, one a line:

    <id> <symbol> <categories>     # e.g.  26 ENG_SLOOP_ANALOG BBBBBLLPPPP...

  id          the engine's number, 22..31 (patches/03-engine-slots.patch): fixed for good (sounds are saved by it),
              each source its own range, never two sources on one id
  symbol      the engine (an engine_t) the source's <source>.c defines
  categories  a letter per preset (browse.c CAT_LETTER: B bass, L lead, P pad, K keys, ...), or - (all OTHER)

A source also needs <source>.c (included into the firmware: its engines, their adapter) and LICENSE. Its units.txt (if
any) lists its own .c files to build as separate units, so their names never meet Melodee's (OUT_DIR/ext_units.txt).
A folder whose name starts with "_" or ".", or that has a file DISABLED, is left out. Removing a source:
delete its folder (or add DISABLED) and rebuild; nothing else changes.

Writes OUT_DIR/ext_engines_ids.h (numbers only: core.h) and OUT_DIR/ext_engines.h (the sources' code and the
tables: engines.c).
"""
import re
import sys
from pathlib import Path

FIRST, LAST = 22, 31          # (upreset.c: NENGINES <= 32)

root, out = Path(sys.argv[1]), Path(sys.argv[2])
engines, sources, fails = [], [], []
for d in sorted((root / "engines").iterdir()) if (root / "engines").is_dir() else []:
    if not d.is_dir() or d.name[0] in "_." or (d / "DISABLED").exists() or not (d / "engines.txt").exists():
        continue
    if not (d / "LICENSE").exists():
        fails.append(f"{d.name}: no LICENSE")
    if not (d / f"{d.name}.c").exists():
        fails.append(f"{d.name}: no {d.name}.c")
    sources.append(d)
    for n, line in enumerate((d / "engines.txt").read_text().splitlines(), 1):
        line = line.split("#")[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 3 or not parts[0].isdigit() or not re.fullmatch(r"[A-Za-z_]\w*", parts[1]):
            fails.append(f"{d.name}/engines.txt:{n}: expected <id> <symbol> <categories>")
            continue
        eid, sym, cats = int(parts[0]), parts[1], parts[2]
        if not FIRST <= eid <= LAST:
            fails.append(f"{d.name}/engines.txt:{n}: id {eid} outside {FIRST}..{LAST}")
        if not re.fullmatch(r"-|[?BLPUKDFOGSRWE]+", cats):
            fails.append(f"{d.name}/engines.txt:{n}: categories: letters of ?BLPUKDFOGSRWE, or -")
        engines.append((eid, sym, cats, d.name))
seen = {}
for eid, sym, _, src in engines:
    if eid in seen:
        fails.append(f"id {eid}: {seen[eid]} and {src}")
    seen[eid] = src
for f in fails:
    print("gen_ext_engines:", f)
if fails:
    sys.exit(1)

out.mkdir(parents=True, exist_ok=True)
ids = ["/* generated by scripts/gen_ext_engines.py: the engines from engines/ (numbers only) */", "#pragma once",
       f"#define EXT_ENGINE_FIRST {FIRST}u", f"#define EXT_ENGINE_COUNT {len(engines)}u"]
(out / "ext_engines_ids.h").write_text("\n".join(ids) + "\n")

code = ["/* generated by scripts/gen_ext_engines.py: the engines from engines/, their code and the tables */",
        "#pragma once"]
code += [f'#include "{(d / (d.name + ".c")).resolve()}"   /* {d.name} */' for d in sources]
code.append("#define EXT_ENGINE_TABLE " + "".join(f"[{e}] = &{s}, " for e, s, _, _ in engines))
code.append("#define EXT_ENGINE_IDS " + "".join(f"{e}, " for e, _, _, _ in sorted(engines)))
code.append("#define EXT_PRESET_CATS " + "".join(f'[{e}] = "{c}", ' for e, _, c, _ in engines if c != "-"))
code.append("static void ext_engines_init(void)                 /* (web_boot: before anything plays) */\n{")
code += [f"    {d.name}_init();" for d in sources]
code.append("}")
code.append("static void ext_preset_loaded(struct track *t, uint32_t e, uint32_t k)   /* (apply_preset_to) */\n{")
code += [f"    {d.name}_preset_loaded(t, e, k);" for d in sources]
code.append("    (void)t; (void)e; (void)k;\n}")
(out / "ext_engines.h").write_text("\n".join(code) + "\n")
units = []                     # a source's own files built as units of their own (units.txt), with -I firmware/src/x0x
for d in sources:
    if (d / "units.txt").exists():
        for line in (d / "units.txt").read_text().splitlines():
            line = line.split("#")[0].strip()
            if line:
                if not (d / line).exists():
                    print(f"gen_ext_engines: {d.name}/units.txt: no {line}"); sys.exit(1)
                units.append(str((d / line).resolve()))
(out / "ext_units.txt").write_text("".join(f"{u}\n" for u in units))
names = ", ".join(f"{s} ({e}, {src})" for e, s, _, src in sorted(engines))
print(f"gen_ext_engines: {len(engines)} engine{'s' * (len(engines) != 1)} from {len(sources)} source{'s' * (len(sources) != 1)}"
      + (f": {names}" if engines else ""))
